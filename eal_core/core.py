"""EAL-CORE: central system architecture and lifecycle management.

Coordinates subsystem initialization, start/stop lifecycle, and wiring between
the event bus, agent registry, and configuration. ``EALCore`` is the single
entry point for creating and tearing down an EAL instance.

It imports nothing from the feature modules (eal_cl, eal_brain, ...), keeping
the core minimal and testable in isolation.
"""

from __future__ import annotations

from typing import Any

from .config import Config
from .event_bus import Event, EventBus, CORE_IDENTITY
from .identity import AgentIdentity
from .registry import AgentRegistry


class EALCore:
    """Central coordinator for the EAL ecosystem.

    Attributes:
        config: Validated configuration snapshot.
        bus: The event bus all modules communicate over.
        registry: Live agent registry keyed by identity.
    """

    def __init__(self, config: Config | None = None) -> None:
        self.config = config or Config()
        self.bus = EventBus()
        self.registry: AgentRegistry[Any] = AgentRegistry(
            max_agents=self.config.max_agents,
            event_bus=self.bus,
        )
        self._running = False

    # -- lifecycle --------------------------------------------------------

    def start(self) -> None:
        """Start the EAL core and emit a system-started event."""
        if self._running:
            return
        self._running = True
        self.bus.publish(
            "system.started",
            {
                "experiment_name": self.config.experiment_name,
                "seed": self.config.seed,
                "modules": sorted(self.config.modules),
                "nvidia_acceleration": self.config.nvidia_acceleration,
            },
            source=CORE_IDENTITY,
        )

    def stop(self) -> None:
        """Stop the EAL core, dropping all agents and emitting system.stopped."""
        if not self._running:
            return
        self.registry.clear()
        self._running = False
        self.bus.publish(
            "system.stopped",
            {"experiment_name": self.config.experiment_name},
            source=CORE_IDENTITY,
        )

    @property
    def running(self) -> bool:
        """Whether the core has been started and not stopped."""
        return self._running

    # -- agent management -------------------------------------------------

    def register_agent(self, instance: Any,
                       metadata: dict[str, Any] | None = None) -> AgentIdentity:
        """Register a live agent instance and return its identity.

        The identity is generated by the core; agents cannot choose their own
        identifier, which prevents impersonation.
        """
        identity = AgentIdentity.generate()
        self.registry.register(identity, instance, metadata=metadata)
        return identity

    def get_agent(self, identity: AgentIdentity) -> Any | None:
        """Return the live agent instance for ``identity``, or ``None``."""
        return self.registry.get_instance(identity)

    def drop_agent(self, identity: AgentIdentity) -> bool:
        """Drop ``identity`` from the registry. Returns True if removed."""
        return self.registry.drop(identity) is not None

    # -- event emission ---------------------------------------------------

    def emit(self, event_type: str, payload: dict[str, Any],
             source: AgentIdentity = CORE_IDENTITY,
             correlation_id: str | None = None) -> Event:
        """Publish an event on the core event bus."""
        return self.bus.publish(
            event_type, payload, source=source, correlation_id=correlation_id
        )
